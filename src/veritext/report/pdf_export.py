"""PDF report exporter using fpdf2 with robust non-Latin character handling and visual gauges."""

from pathlib import Path
import re
from typing import Optional, Set, Union

from fpdf import FPDF
from fpdf.enums import XPos, YPos

from veritext.report.diff import extract_report_diffs
from veritext.report.models import FullReport
from veritext.report.seal import compute_seal

REPLACE_MAP = {
    "\u201c": '"',
    "\u201d": '"',
    "\u2018": "'",
    "\u2019": "'",
    "\u2014": "-",
    "\u2013": "-",
    "\u2026": "...",
    "\u200b": "",  # zero-width space
    "\u200c": "",
    "\u200d": "",
    "\u2060": "",
    "\ufeff": "",
    "\u00ad": "-",  # soft hyphen
    "\t": "    ",
}


def sanitize_text_for_pdf(text: str) -> str:
    """Sanitizes text for PDF generation by replacing punctuation and encoding unknown chars."""
    if not text:
        return ""

    out = text
    for k, v in REPLACE_MAP.items():
        out = out.replace(k, v)

    # Encode to latin-1, replacing any unrepresentable characters with '?'
    clean_bytes = out.encode("latin-1", errors="replace")
    return clean_bytes.decode("latin-1")


class VeritextPDF(FPDF):
    """Custom PDF class with styled headers and footers."""

    def __init__(self, doc_name: str = ""):
        super().__init__()
        self.doc_name = doc_name

    def header(self):
        self.set_font("Helvetica", "B", 8)
        self.set_text_color(100, 116, 139)
        self.cell(0, 6, "VERITEXT ACADEMIC INTEGRITY REPORT", new_x=XPos.RIGHT, new_y=YPos.TOP, align="L")
        clean_name = sanitize_text_for_pdf(self.doc_name)[:40]
        self.cell(0, 6, clean_name, new_x=XPos.LMARGIN, new_y=YPos.NEXT, align="R")
        self.set_draw_color(226, 232, 240)
        self.line(10, 16, 200, 16)
        self.ln(4)

    def footer(self):
        self.set_y(-14)
        self.set_font("Helvetica", "", 8)
        self.set_text_color(148, 163, 184)
        self.cell(0, 6, f"Page {self.page_no()}/{{nb}} - Generated by Veritext (Offline & Open-Source)", align="C")


def export_report_pdf(
    report: FullReport,
    output_path: Optional[Union[str, Path]] = None,
    ignored_ids: Optional[Set[str]] = None,
) -> bytes:
    """Exports a compact, accessible PDF report.

    Args:
        report: FullReport object.
        output_path: Optional file path to write PDF output to disk.
        ignored_ids: Optional set of dismissed highlight IDs.

    Returns:
        Generated PDF bytes.
    """
    ignored = ignored_ids or set()
    pdf = VeritextPDF(doc_name=report.document_name)
    pdf.alias_nb_pages()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    # 1. Document Title
    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(15, 23, 42)
    pdf.cell(0, 10, "Integrity & Verification Report", new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(100, 116, 139)
    meta_line = f"Document: {sanitize_text_for_pdf(report.document_name)}   |   Timestamp: {report.timestamp[:19]}"
    pdf.cell(0, 5, meta_line, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.ln(4)

    # 2. Score Gauges Panel
    pdf.set_fill_color(248, 250, 252)
    pdf.set_draw_color(226, 232, 240)
    pdf.rect(10, pdf.get_y(), 190, 36, style="FD")
    start_y = pdf.get_y() + 4

    # Plagiarism Gauge
    sim_val = report.similarity.similarity_percentage if report.similarity else 0.0
    pdf.set_xy(16, start_y)
    pdf.set_font("Helvetica", "B", 9)
    pdf.set_text_color(71, 85, 105)
    pdf.cell(50, 5, "Plagiarism Similarity:", new_x=XPos.RIGHT, new_y=YPos.TOP)
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(220, 38, 38)
    pdf.cell(20, 5, f"{sim_val:.1f}%", new_x=XPos.RIGHT, new_y=YPos.TOP)

    # Bar
    pdf.set_xy(90, start_y + 1)
    pdf.set_fill_color(226, 232, 240)
    pdf.rect(90, start_y + 1, 95, 4, style="F")
    if sim_val > 0:
        fill_w = min(95.0, (sim_val / 100.0) * 95.0)
        pdf.set_fill_color(220, 38, 38)
        pdf.rect(90, start_y + 1, fill_w, 4, style="F")

    # AI Probability Gauge
    pdf.set_xy(16, start_y + 10)
    pdf.set_font("Helvetica", "B", 9)
    pdf.set_text_color(71, 85, 105)
    pdf.cell(50, 5, "AI-Text Probability:", new_x=XPos.RIGHT, new_y=YPos.TOP)

    if not report.ai_detect:
        pdf.set_font("Helvetica", "B", 10)
        pdf.set_text_color(100, 116, 139)
        pdf.cell(100, 5, "Not run", new_x=XPos.RIGHT, new_y=YPos.TOP)
    elif getattr(report.ai_detect, "status", "success") in ("insufficient text", "insufficient_text"):
        pdf.set_font("Helvetica", "B", 9)
        pdf.set_text_color(100, 116, 139)
        pdf.cell(120, 5, "Insufficient text (under 150 words, not scored)", new_x=XPos.RIGHT, new_y=YPos.TOP)
    else:
        ai_raw = getattr(report.ai_detect, "overall_probability", getattr(report.ai_detect, "ai_probability", 0.0))
        ai_val = float(ai_raw) if ai_raw is not None else 0.0
        ai_conf = getattr(report.ai_detect, "confidence_band", getattr(report.ai_detect, "confidence", "none")).lower()
        pdf.set_font("Helvetica", "B", 10)
        pdf.set_text_color(124, 58, 237)
        pdf.cell(18, 5, f"{ai_val:.1f}%", new_x=XPos.RIGHT, new_y=YPos.TOP)
        pdf.set_font("Helvetica", "", 8)
        pdf.set_text_color(100, 116, 139)
        pdf.cell(55, 5, f"(confidence in this estimate: {ai_conf})", new_x=XPos.RIGHT, new_y=YPos.TOP)

        pdf.set_xy(140, start_y + 11)
        pdf.set_fill_color(226, 232, 240)
        pdf.rect(140, start_y + 11, 45, 4, style="F")
        if ai_val > 0:
            fill_w = min(45.0, (ai_val / 100.0) * 45.0)
            pdf.set_fill_color(124, 58, 237)
            pdf.rect(140, start_y + 11, fill_w, 4, style="F")

    # Integrity Findings Summary
    high_cnt = sum(sum(1 for f in r.findings if f.severity == "high") for r in report.integrity.results) if report.integrity else 0
    warn_cnt = sum(sum(1 for f in r.findings if f.severity == "warning") for r in report.integrity.results) if report.integrity else 0
    info_cnt = sum(sum(1 for f in r.findings if f.severity == "info") for r in report.integrity.results) if report.integrity else 0

    pdf.set_xy(16, start_y + 20)
    pdf.set_font("Helvetica", "B", 9)
    pdf.set_text_color(71, 85, 105)
    pdf.cell(50, 5, "Integrity Findings:", new_x=XPos.RIGHT, new_y=YPos.TOP)
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(15, 23, 42)
    findings_line = f"{high_cnt} High Severity   |   {warn_cnt} Warning   |   {info_cnt} Informational"
    pdf.cell(100, 5, findings_line, new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    pdf.set_y(start_y + 32)
    pdf.ln(4)

    # 3. Limitations Disclaimer Box
    pdf.set_fill_color(255, 251, 235)
    pdf.set_draw_color(253, 230, 138)
    disc_text = (
        "LIMITATIONS & RESPONSIBLE USE NOTICE: Verification scores are automated indicators to guide "
        "human pedagogical review and do not prove misconduct or generative authorship."
    )
    pdf.set_font("Helvetica", "", 8)
    pdf.set_text_color(146, 64, 14)
    pdf.multi_cell(190, 4, disc_text, border=1, fill=True)
    pdf.ln(5)

    # 4. Executive Summary
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(15, 23, 42)
    pdf.cell(0, 6, "Executive Summary", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.set_font("Helvetica", "", 9)
    pdf.multi_cell(190, 4.5, sanitize_text_for_pdf(report.summary))

    # Active Exclusion Filters
    active_filters = (
        report.settings.get("active_filters")
        or (report.similarity.metadata.get("active_filters") if report.similarity and report.similarity.metadata else None)
        or ["Standard exclusions (small matches <25 chars)"]
    )
    pdf.ln(2)
    pdf.set_font("Helvetica", "B", 8)
    pdf.set_text_color(71, 85, 105)
    pdf.cell(38, 4, "Active Exclusion Filters: ", new_x=XPos.RIGHT, new_y=YPos.TOP)
    pdf.set_font("Helvetica", "", 8)
    pdf.multi_cell(152, 4, sanitize_text_for_pdf(", ".join(active_filters)))
    pdf.ln(3)
    pdf.ln(5)

    # 4b. Document Profile & Plan Coverage
    if report.profile or report.plan:
        pdf.set_font("Helvetica", "B", 10)
        pdf.set_text_color(15, 23, 42)
        pdf.cell(0, 5.5, "Document Profile & Adaptive Engine Coverage", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.set_font("Helvetica", "", 8.5)
        pdf.set_text_color(51, 65, 85)

        if report.profile:
            p = report.profile
            prof_str = (
                f"Words: {p.get('word_count', 0):,}   |   "
                f"Characters: {p.get('character_count', 0):,}   |   "
                f"Pages: {p.get('page_estimate', 1):,}   |   "
                f"Size Class: {str(p.get('size_class', '')).upper()}   |   "
                f"Language: {p.get('language_guess', 'en')}"
            )
            pdf.cell(0, 4.5, prof_str, new_x=XPos.LMARGIN, new_y=YPos.NEXT)

        if report.plan:
            pl_engines = report.plan.get("engines", {})
            for eng_k, eng_v in pl_engines.items():
                cov_desc = eng_v.get("coverage_description", "full document analysed")
                pdf.cell(0, 4.5, f"- {eng_k.replace('_', ' ').title()}: {cov_desc}", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.ln(4)

    # 5. Matched Sources Table
    if report.similarity and report.similarity.sources:
        pdf.set_font("Helvetica", "B", 11)
        pdf.cell(0, 6, "Matched Sources Summary", new_x=XPos.LMARGIN, new_y=YPos.NEXT)

        # Header
        pdf.set_font("Helvetica", "B", 8)
        pdf.set_fill_color(241, 245, 249)
        pdf.set_text_color(51, 65, 85)
        pdf.cell(90, 6, "Source Title", border=1, fill=True)
        pdf.cell(30, 6, "Origin", border=1, fill=True)
        pdf.cell(35, 6, "Matched Chars", border=1, fill=True)
        pdf.cell(35, 6, "Overlap %", border=1, fill=True)
        pdf.ln(6)

        pdf.set_font("Helvetica", "", 8)
        pdf.set_text_color(15, 23, 42)
        for s in report.similarity.sources[:8]:
            title_clean = sanitize_text_for_pdf(s.source_title)[:48]
            pdf.cell(90, 5.5, title_clean, border=1)
            pdf.cell(30, 5.5, sanitize_text_for_pdf(s.origin), border=1)
            pdf.cell(35, 5.5, f"{s.matched_chars} chars", border=1)
            pdf.cell(35, 5.5, f"{s.percentage:.1f}%", border=1)
            pdf.ln(5.5)
        pdf.ln(5)

    # 6. Top Matched Passages Excerpts (Top 10)
    active_matches = [
        h for h in report.highlights
        if h.id not in ignored and h.category in ("exact match", "paraphrase", "possible paraphrase (review)")
    ][:10]

    if active_matches:
        pdf.set_font("Helvetica", "B", 11)
        pdf.cell(0, 6, "Top Matched Passages (Excerpts)", new_x=XPos.LMARGIN, new_y=YPos.NEXT)

        pdf.set_font("Helvetica", "B", 8)
        pdf.set_fill_color(241, 245, 249)
        pdf.set_text_color(51, 65, 85)
        pdf.cell(20, 6, "Offsets", border=1, fill=True)
        pdf.cell(25, 6, "Type", border=1, fill=True)
        pdf.cell(45, 6, "Matched Source", border=1, fill=True)
        pdf.cell(100, 6, "Document Excerpt", border=1, fill=True)
        pdf.ln(6)

        pdf.set_font("Helvetica", "", 7.5)
        pdf.set_text_color(15, 23, 42)
        for m in active_matches:
            excerpt = report.original_text[m.start:m.end].replace("\n", " ").strip()
            excerpt_clean = sanitize_text_for_pdf(excerpt)[:75]
            src_clean = sanitize_text_for_pdf(m.source or "Source")[:25]
            offsets_str = f"{m.start}:{m.end}"

            pdf.cell(20, 5, offsets_str, border=1)
            pdf.cell(25, 5, sanitize_text_for_pdf(m.category), border=1)
            pdf.cell(45, 5, src_clean, border=1)
            pdf.cell(100, 5, excerpt_clean, border=1)
            pdf.ln(5)
        pdf.ln(5)

    # 7. AI Sentence Highlights (Top 5)
    if report.ai_detect and report.ai_detect.sentences:
        pdf.set_font("Helvetica", "B", 11)
        pdf.cell(0, 6, "Top AI-Like Sentences", new_x=XPos.LMARGIN, new_y=YPos.NEXT)

        pdf.set_font("Helvetica", "B", 8)
        pdf.set_fill_color(241, 245, 249)
        pdf.set_text_color(51, 65, 85)
        pdf.cell(20, 6, "Offsets", border=1, fill=True)
        pdf.cell(25, 6, "AI Score", border=1, fill=True)
        pdf.cell(30, 6, "Classification", border=1, fill=True)
        pdf.cell(115, 6, "Sentence Excerpt", border=1, fill=True)
        pdf.ln(6)

        pdf.set_font("Helvetica", "", 7.5)
        pdf.set_text_color(15, 23, 42)
        sorted_sents = sorted(report.ai_detect.sentences, key=lambda s: s.score, reverse=True)[:5]
        for s in sorted_sents:
            s_clean = sanitize_text_for_pdf(s.text.replace("\n", " ").strip())[:85]
            s_start = getattr(s, "doc_start", getattr(s, "start", 0))
            s_end = getattr(s, "doc_end", getattr(s, "end", 0))
            pdf.cell(20, 5, f"{s_start}:{s_end}", border=1)
            pdf.cell(25, 5, f"{s.score:.1%}", border=1)
            pdf.cell(30, 5, sanitize_text_for_pdf(s.label), border=1)
            pdf.cell(115, 5, s_clean, border=1)
            pdf.ln(5)
        pdf.ln(5)

    # 8. Integrity Findings
    if report.integrity and report.integrity.results:
        pdf.set_font("Helvetica", "B", 11)
        pdf.cell(0, 6, "Document Integrity & Formatting Anomalies", new_x=XPos.LMARGIN, new_y=YPos.NEXT)

        pdf.set_font("Helvetica", "B", 8)
        pdf.set_fill_color(241, 245, 249)
        pdf.set_text_color(51, 65, 85)
        pdf.cell(30, 6, "Check Module", border=1, fill=True)
        pdf.cell(22, 6, "Severity", border=1, fill=True)
        pdf.cell(22, 6, "Offsets", border=1, fill=True)
        pdf.cell(116, 6, "Description", border=1, fill=True)
        pdf.ln(6)

        pdf.set_font("Helvetica", "", 7.5)
        pdf.set_text_color(15, 23, 42)
        count = 0
        for cr in report.integrity.results:
            for f in cr.findings[:6]:
                count += 1
                msg_clean = sanitize_text_for_pdf(f.message)[:85]
                pdf.cell(30, 5, sanitize_text_for_pdf(f.check), border=1)
                pdf.cell(22, 5, f.severity.upper(), border=1)
                pdf.cell(22, 5, f"{f.start}:{f.end}", border=1)
                pdf.cell(116, 5, msg_clean, border=1)
                pdf.ln(5)
                if count >= 8:
                    break
            if count >= 8:
                break
        pdf.ln(5)

    # 8b. Instructor Rubric Assessment (if present)
    rubric_data = report.metadata.get("rubric") or (
        report.metadata.get("review_session", {}).get("rubric")
        if isinstance(report.metadata.get("review_session"), dict)
        else None
    )
    if rubric_data:
        r_dict = rubric_data if isinstance(rubric_data, dict) else (rubric_data.to_dict() if hasattr(rubric_data, "to_dict") else {})
        r_name = sanitize_text_for_pdf(r_dict.get("name", "Academic Integrity Rubric"))
        r_score = r_dict.get("total_score", 0)
        r_max = r_dict.get("max_possible", 16)
        r_pct = r_dict.get("percentage", 0.0)

        pdf.set_font("Helvetica", "B", 11)
        pdf.cell(0, 6, f"Instructor Rubric Assessment: {r_name}", new_x=XPos.LMARGIN, new_y=YPos.NEXT)

        pdf.set_font("Helvetica", "B", 8)
        pdf.set_fill_color(241, 245, 249)
        pdf.set_text_color(51, 65, 85)
        pdf.cell(60, 6, "Criterion", border=1, fill=True)
        pdf.cell(30, 6, "Score", border=1, fill=True)
        pdf.cell(100, 6, "Reviewer Comments", border=1, fill=True)
        pdf.ln(6)

        pdf.set_font("Helvetica", "", 8)
        pdf.set_text_color(15, 23, 42)
        for crit_id, sc in r_dict.get("scores", {}).items():
            c_name = sanitize_text_for_pdf(crit_id.replace("_", " ").title())
            s_val = sc.get("score", 0) if isinstance(sc, dict) else getattr(sc, "score", 0)
            s_comm = sanitize_text_for_pdf(sc.get("comment", "") if isinstance(sc, dict) else getattr(sc, "comment", ""))[:65]
            pdf.cell(60, 5, c_name, border=1)
            pdf.cell(30, 5, f"{s_val} / 4", border=1)
            pdf.cell(100, 5, s_comm or "-", border=1)
            pdf.ln(5)

        pdf.set_font("Helvetica", "B", 8.5)
        pdf.cell(190, 5, f"Overall Rubric Score: {r_score} / {r_max} ({r_pct:.1f}%)", border=1)
        pdf.ln(7)

    # 8c. Grammar & Style Feedback (if present)
    style_meta = report.metadata.get("style")
    if style_meta:
        s_dict = style_meta if isinstance(style_meta, dict) else (style_meta.to_dict() if hasattr(style_meta, "to_dict") else {})
        metrics = s_dict.get("metrics") or {}
        flesch = metrics.get("flesch_reading_ease", 0.0)
        fog = metrics.get("gunning_fog", 0.0)
        ease_label = sanitize_text_for_pdf(metrics.get("reading_ease_label", "Standard"))
        level = sanitize_text_for_pdf(metrics.get("reading_level", "College"))

        pdf.set_font("Helvetica", "B", 10)
        pdf.cell(0, 5, "Grammar & Style Feedback (Informational)", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.set_font("Helvetica", "", 8)
        pdf.set_text_color(71, 85, 105)
        pdf.cell(0, 4, f"Flesch Reading Ease: {flesch:.1f} ({ease_label})  |  Gunning Fog Index: {fog:.1f} ({level})", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.ln(3)

    # 8d. Compact Source Diffs (Top 10 matches)
    diff_items = extract_report_diffs(report, max_matches=10)
    if diff_items:
        pdf.set_font("Helvetica", "B", 10)
        pdf.cell(0, 5, "Source Match Comparisons (Top 10 Matches)", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.set_font("Helvetica", "", 7.5)
        pdf.set_text_color(100, 116, 139)
        pdf.cell(0, 4, "Bounded side-by-side excerpts showing shared passages (max 1,500 chars).", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.ln(2)

        pdf.set_font("Helvetica", "B", 7.5)
        pdf.set_fill_color(241, 245, 249)
        pdf.set_text_color(51, 65, 85)
        pdf.cell(45, 5, "Source Title", border=1, fill=True)
        pdf.cell(20, 5, "Type", border=1, fill=True)
        pdf.cell(62, 5, "Target Excerpt", border=1, fill=True)
        pdf.cell(63, 5, "Matched Source Reference", border=1, fill=True)
        pdf.ln(5)

        pdf.set_font("Helvetica", "", 7)
        pdf.set_text_color(15, 23, 42)
        for d in diff_items:
            s_title = sanitize_text_for_pdf(d.source_title)[:25]
            m_type = sanitize_text_for_pdf(d.match_type).upper()
            t_exc = sanitize_text_for_pdf(d.target_excerpt)[:120]
            if d.is_fingerprint_only or d.source_excerpt is None:
                s_exc = "source text not stored (fingerprints only)"
            else:
                s_exc = sanitize_text_for_pdf(d.source_excerpt)[:120]

            pdf.cell(45, 5, s_title, border=1)
            pdf.cell(20, 5, m_type, border=1)
            pdf.cell(62, 5, t_exc, border=1)
            pdf.cell(63, 5, s_exc, border=1)
            pdf.ln(5)
        pdf.ln(4)

    # 8e. Tamper-Evident Seal Block
    seal_info = report.seal or compute_seal(report.to_dict())
    pdf.set_font("Helvetica", "B", 9)
    pdf.set_text_color(5, 150, 105)
    pdf.cell(0, 5, "[SEALED] Cryptographic Tamper-Evident Report Seal", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.set_font("Helvetica", "", 7.5)
    pdf.set_text_color(71, 85, 105)
    c_sha = seal_info.get("canonical_sha256", "")
    sig = seal_info.get("signature", "")
    pdf.multi_cell(
        190,
        3.8,
        f"Algorithm: {seal_info.get('algorithm', 'HMAC-SHA256')}  |  Canonical SHA-256: {c_sha[:32]}...\n"
        f"HMAC-SHA256 Signature: {sig[:32]}...\n"
        f"Notice: Detects unauthorized edits without local signing key. Not legal proof. CLI: python -m veritext.report verify <file.json>",
    )
    pdf.ln(3)

    # 9. Methodology & Settings
    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(0, 5, "Methodology & Engine Settings", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.set_font("Helvetica", "", 8)
    pdf.set_text_color(100, 116, 139)
    method_str = (
        f"Analysis performed offline using Veritext multi-engine pipeline. "
        f"Total document words: {report.metadata.get('word_count', 0)}, "
        f"Total characters: {report.metadata.get('character_count', 0)}."
    )
    pdf.multi_cell(190, 4, method_str)

    # Render PDF output bytes
    pdf_bytes = bytes(pdf.output())

    if output_path:
        out_file = Path(output_path)
        out_file.parent.mkdir(parents=True, exist_ok=True)
        out_file.write_bytes(pdf_bytes)

    return pdf_bytes
